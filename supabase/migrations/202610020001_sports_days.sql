do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'teams', 'competitors', 'point_profiles', 'events', 'event_runs',
        'results', 'matches', 'race_results', 'event_competitors',
        'distance_results', 'double_team_matches', 'attempts'
    ] loop
        execute format(
            'alter table public.%I alter column sports_day_id set not null',
            table_name
        );
        execute format(
            'create index %I on public.%I (sports_day_id)',
            table_name || '_sports_day_id_idx',
            table_name
        );
    end loop;
end;
$$;

