-- Group each annual competition so a new Sports Day never overwrites history.

create table public.sports_days (
    id text primary key,
    name text not null,
    is_active boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    source_order bigint generated by default as identity unique,
    constraint sports_days_id_not_blank check (btrim(id) <> ''),
    constraint sports_days_name_not_blank check (btrim(name) <> ''),
    constraint sports_days_name_length check (char_length(name) <= 80)
);

create unique index sports_days_name_case_insensitive_idx
    on public.sports_days (lower(btrim(name)));
create unique index sports_days_one_active_idx
    on public.sports_days (is_active)
    where is_active;

